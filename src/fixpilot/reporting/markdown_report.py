"""FixPilot AI Markdown Report Generator.

Generates comprehensive markdown reports for repair runs according to PROJECT_SPEC §12.
"""

from typing import Any, Dict, List, Optional
from fixpilot.schemas.state import FixPilotState


def generate_markdown_report(
    run_data: Dict[str, Any],
    attempts: Optional[List[Dict[str, Any]]] = None,
) -> str:
    """Generate a clean markdown report from run metadata and attempts."""
    attempts = attempts or []
    run_id = run_data.get("run_id", "unknown")
    status = str(run_data.get("status", "UNKNOWN")).upper()

    lines = [
        f"# FixPilot AI Repair Report",
        f"**Run ID:** `{run_id}`  ",
        f"**Status:** **{status}**  ",
        f"**Version:** 0.1.0",
        "",
        "## Summary",
        f"- **Target Project:** `{run_data.get('target_display_path', 'N/A')}`",
        f"- **Mode:** {run_data.get('mode', 'standard')}",
        f"- **Model:** {run_data.get('model_name', 'default')}",
        f"- **Started At:** {run_data.get('started_at', 'N/A')}",
        f"- **Finished At:** {run_data.get('finished_at', 'N/A')}",
        f"- **Baseline Exit Code:** {run_data.get('baseline_exit_code', 'N/A')}",
        f"- **Final Exit Code:** {run_data.get('final_exit_code', 'N/A')}",
        f"- **Total Attempts:** {len(attempts)}",
        "",
    ]

    if run_data.get("error_summary"):
        lines.extend([
            "## Error Summary",
            f"```text\n{run_data.get('error_summary')}\n```",
            "",
        ])

    lines.append("## Attempt Details")
    if not attempts:
        lines.append("*No attempts were recorded for this run.*")
    else:
        for attempt in attempts:
            num = attempt.get("attempt_number", 1)
            v_status = str(attempt.get("verification_status", "N/A")).upper()
            t_status = str(attempt.get("test_status", "N/A")).upper()
            app_status = str(attempt.get("approval_status", "N/A")).upper()

            lines.extend([
                f"### Attempt {num}",
                f"- **Verification Outcome:** `{v_status}`",
                f"- **Test Status:** `{t_status}`",
                f"- **Approval:** `{app_status}`",
                f"- **Root Cause:** {attempt.get('root_cause_summary', 'N/A')}",
                f"- **Patch Summary:** {attempt.get('patch_summary', 'N/A')}",
                f"- **Timestamp:** {attempt.get('created_at', 'N/A')}",
                "",
            ])

            patch_content = attempt.get("patch_path") or attempt.get("patch")
            if patch_content:
                lines.extend([
                    "**Applied Patch Diff:**",
                    "```diff",
                    patch_content.strip(),
                    "```",
                    "",
                ])

    lines.extend([
        "---",
        "## Notice & Limitations",
        "- Repairs are validated against the defined test suite only.",
        "- Passing tests do not formally guarantee absence of defects.",
        "- FixPilot AI should be monitored for production changes.",
        "",
        "*Report automatically generated by FixPilot AI*",
    ])

    return "\n".join(lines)

